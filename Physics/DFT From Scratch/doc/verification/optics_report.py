"""Writes the figure data and the numbers quoted in Chapters 12-13:
   python3 optics_report.py optics_40_30_soc.npz optics_24_40_soc.npz
-> ../figdata/optics_spec.dat, ../figdata/optics_numbers.tex"""
import sys, numpy as np
from optics_post import *
mu = 0.5832153855388598
fine, coarse = sys.argv[1], sys.argv[2]
A = analyse(fine, mu, verbose=False); B = analyse(coarse, mu, verbose=False)
S = {sc: analyse(fine, mu, scissor_eV=sc, verbose=False) for sc in (0.5, 0.75)}
Dr = analyse(fine, mu, inter=False, verbose=False)
H = analyse(fine, mu, eta_eV=0.2, verbose=False)
hw = A['hw']
np.savetxt('../figdata/optics_spec.dat', np.c_[hw, A['e1'], A['e2'], A['e2i'], A['R'], S[0.5]['R'], S[0.75]['R'], Dr['R'], B['R'], B['e2i']][4::2],
           fmt='%.4f', header='hw_eV eps1 eps2 eps2_inter R R_shift0.5 R_shift0.75 R_drude R_coarse eps2i_coarse', comments='')
sig = 1/2.2e-8/AU_COND                               # measured sigma (rho = 2.2 micro-ohm cm) in a.u.
tau = 4*pi*sig/A['wp2']; kT = 295*3.166811563e-6
def edge(o):                                          # photon energy where R falls through 0.7 (first time)
    i = np.argmax(o['R'] < 0.7); return o['hw'][i]
def onset(o):
    i = np.argmax(o['e2i'] > 2.0); return o['hw'][i]
m = {'GF': '%.3f' % B['gF'], 'GFb': '%.3f' % A['gF'], 'VF': '%.2f' % (B['vF']/1e6), 'VFb': '%.2f' % (A['vF']/1e6),
     'WP': '%.2f' % B['wp'], 'WPb': '%.2f' % A['wp'],
     'ST': '%.2f' % (B['wp2']/(4*pi)*AU_COND/AU_TIME_FS/1e6), 'STb': '%.2f' % (A['wp2']/(4*pi)*AU_COND/AU_TIME_FS/1e6),
     'NEFF': '%.2f' % (A['wp2']*A['Om']/(4*pi)), 'TAU': '%.0f' % (tau*AU_TIME_FS), 'MFP': '%.0f' % (A['vF']*tau*AU_TIME_FS*1e-15*1e9),
     'LAMTR': '%.2f' % (1/(2*pi*tau*kT)), 'NKFINE': '%d' % A['nk'], 'NKCOARSE': '%d' % B['nk'], 'NTRANS': '%d' % round(A['ntrans']/1e3),
     'EDGE': '%.1f' % edge(A), 'ONSET': '%.1f' % onset(A), 'EDGES': '%.1f' % edge(S[0.75]),
     'EPSZERO': '%.1f' % A['e1i'][0],
     'NEFFINTER': '%.1f' % (A['Om']/(2*pi**2)*np.trapezoid(hw/HA*A['e2i'], hw/HA))}
for nm, o in (('LDA', A), ('SHa', S[0.5]), ('SHb', S[0.75]), ('DR', Dr), ('CO', B), ('ETA', H)):
    m['RGB'+nm] = '%d,%d,%d' % tuple(o['rgb'])
    for l in (450, 550, 650): m['R%s%s' % (nm, {450: 'b', 550: 'g', 650: 'r'}[l])] = '%.2f' % o['Rl'](l)
with open('../figdata/optics_numbers.tex', 'w') as f:
    f.write("% generated by verification/optics_report.py -- do not edit\n")
    for k, v in m.items(): f.write("\\newcommand{\\%s}{%s}\n" % (k, v))
    for nm in ('LDA', 'SHa', 'SHb', 'DR'): f.write("\\definecolor{gold%s}{RGB}{%s}\n" % (nm, m['RGB'+nm]))
# measured optical constants (Johnson & Christy 1972, via refractiveindex.info, CC0)
rows = [l.split() for l in open('reference_data/Au_Johnson_Christy_1972.yml') if len(l.split()) == 3 and l.strip()[0].isdigit()]
jc = np.array(rows, float); lamx = jc[:, 0]*1000; nx, kx = jc[:, 1], jc[:, 2]
Rx = ((nx-1)**2+kx**2)/((nx+1)**2+kx**2); hwx = 1239.84193/lamx; o_ = np.argsort(hwx)
np.savetxt('../figdata/optics_exp.dat', np.c_[hwx, nx*nx-kx*kx, 2*nx*kx, Rx][o_], fmt='%.4f', header='hw_eV eps1 eps2 R', comments='')
ol = np.argsort(lamx); Rlx = lambda l: np.interp(l, lamx[ol], Rx[ol])
rgbx = srgb_of_reflectance(Rlx)[2]
e2x = lambda e: np.interp(e, hwx[o_], (2*nx*kx)[o_]); e2c = lambda e: np.interp(e, hw, A['e2'])
with open('../figdata/optics_numbers.tex', 'a') as f:
    f.write("\\newcommand{\\RGBEXP}{%d,%d,%d}\n\\definecolor{goldEXP}{RGB}{%d,%d,%d}\n" % (tuple(rgbx)+tuple(rgbx)))
    f.write("\\newcommand{\\REXPb}{%.2f}\n\\newcommand{\\REXPg}{%.2f}\n\\newcommand{\\REXPr}{%.2f}\n" % (Rlx(450), Rlx(550), Rlx(650)))
    f.write("\\newcommand{\\EDGEEXP}{%.1f}\n" % hwx[o_][np.argmax(Rx[o_] < 0.7)])
    f.write("\\newcommand{\\EPSEXP}{%.1f}\n\\newcommand{\\EPSCALC}{%.1f}\n" % (e2x(3.0), e2c(3.0)))
print("measured: rgb", rgbx, "R(450,550,650)", Rlx(450), Rlx(550), Rlx(650), "eps2(3 eV) exp/calc", e2x(3.0), e2c(3.0), "eps2(3.5)", e2x(3.5), e2c(3.5))
N = analyse('optics_16_40_nosoc.npz', mu, verbose=False); Y = analyse('optics_16_40_soc.npz', mu, verbose=False)
with open('../figdata/optics_numbers.tex', 'a') as f:
    f.write("\\newcommand{\\EDGENOSOC}{%.2f}\n\\newcommand{\\EDGESOC}{%.2f}\n" % (edge(N), edge(Y)))
print("edges nosoc/soc 16^3:", edge(N), edge(Y))
for k, v in m.items(): print(k, v)
